"""Generate docs/dev/API.md: an index of the public API of the :mallet library.

Run from the project root:  python tools/api_index.py [output-path]

For every Kotlin source file it lists the public declarations with their signatures and the
first sentence of their KDoc. It is a reading aid, not a reference: the KDoc in the sources is
the reference.
"""
import io
import os
import re
import sys

ROOT = "mallet/src/main/kotlin/io/github/avalonskyafar/mallet"
ORDER = ["theme", "material", "icon", "widget", "interaction", "overlay"]


def first_sentence(doc_lines):
    text = " ".join(line.strip().lstrip("*").strip() for line in doc_lines)
    text = re.sub(r"\s+", " ", text).strip()
    if not text:
        return ""
    cut = re.search(r"(?<=[.:])\s", text)
    sentence = text[: cut.start()] if cut else text
    return sentence[:200]


def declarations(path):
    with io.open(path, encoding="utf-8") as handle:
        lines = handle.read().split("\n")
    out = []
    doc = []
    in_doc = False
    index = 0
    while index < len(lines):
        raw = lines[index]
        line = raw.strip()
        if line.startswith("/**"):
            doc = [line[3:].replace("*/", "")]
            in_doc = "*/" not in line
            index += 1
            continue
        if in_doc:
            if "*/" in line:
                in_doc = False
                doc.append(line.replace("*/", ""))
            else:
                doc.append(line)
            index += 1
            continue
        if line.startswith("@"):
            index += 1
            continue
        if line.startswith("public ") and not line.startswith("public constructor"):
            signature = line
            depth = signature.count("(") - signature.count(")")
            while depth > 0 and index + 1 < len(lines):
                index += 1
                more = lines[index].strip()
                signature += " " + more
                depth += more.count("(") - more.count(")")
            signature = re.sub(r"\s*\{\s*$", "", signature)
            if signature.startswith(("public val", "public var", "public const")):
                signature = re.sub(r"\s*=\s*[^=].*$", "", signature)
            signature = re.sub(r"\s+", " ", signature).replace("public ", "", 1)
            signature = signature.replace("@JvmOverloads constructor", "").replace("( ", "(").replace(", )", ")")
            indent = len(raw) - len(raw.lstrip())
            out.append((indent, signature, first_sentence(doc)))
        if line and not line.startswith("//"):
            doc = []
        index += 1
    return out


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "docs/dev/API.md"
    parts = ["# Public API index", "",
             "Generated by `tools/api_index.py` from the sources of `:mallet`. One line per public declaration;",
             "indentation shows nesting. Read the KDoc in the source file for the details.", ""]
    for area in ORDER:
        directory = os.path.join(ROOT, area)
        if not os.path.isdir(directory):
            continue
        parts.append("## %s" % area)
        parts.append("")
        for name in sorted(os.listdir(directory)):
            if not name.endswith(".kt"):
                continue
            found = declarations(os.path.join(directory, name))
            if not found:
                continue
            parts.append("### %s/%s" % (area, name))
            parts.append("")
            parts.append("```")
            base = min(indent for indent, _, _ in found)
            for indent, signature, summary in found:
                pad = "  " * ((indent - base) // 4)
                text = pad + signature
                if summary:
                    text += "    // " + summary
                parts.append(text[:260])
            parts.append("```")
            parts.append("")
    with io.open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(parts))
    print("wrote", target, "with", len(parts), "lines")


main()
